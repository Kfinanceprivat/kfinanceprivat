function applyLanguage(lang){
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(translations[key]) el.textContent = translations[key][lang];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el=>{
    const key = el.getAttribute("data-i18n-ph");
    if(translations[key]) el.setAttribute("placeholder", translations[key][lang]);
  });
  document.querySelectorAll(".lang-toggle button").forEach(b=>{
    b.classList.toggle("active", b.dataset.lang === lang);
  });
  localStorage_safeSet("kfp_lang", lang);
}

function localStorage_safeSet(k,v){ try{ /* not used in artifacts, kept no-op safe for real deployment */ }catch(e){} }

document.addEventListener("DOMContentLoaded", ()=>{
  const toggleButtons = document.querySelectorAll(".lang-toggle button");
  toggleButtons.forEach(btn=>{
    btn.addEventListener("click", ()=> applyLanguage(btn.dataset.lang));
  });
  applyLanguage("de");

  /* Sticky header shadow */
  const header = document.querySelector("header.site");
  if(header){
    window.addEventListener("scroll", ()=>{
      header.classList.toggle("scrolled", window.scrollY > 8);
    });
  }

  /* Mobile nav */
  const burger = document.querySelector(".burger");
  const navLinks = document.querySelector(".nav-links");
  const backdrop = document.querySelector(".nav-backdrop");

  function closeMenu(){
    navLinks.classList.remove("mobile-open");
    burger.classList.remove("open");
    if(backdrop) backdrop.classList.remove("show");
  }
  function toggleMenu(){
    const isOpen = navLinks.classList.toggle("mobile-open");
    burger.classList.toggle("open", isOpen);
    if(backdrop) backdrop.classList.toggle("show", isOpen);
  }

  if(burger && navLinks){
    burger.addEventListener("click", toggleMenu);
    navLinks.querySelectorAll("a").forEach(a=> a.addEventListener("click", closeMenu));
    if(backdrop) backdrop.addEventListener("click", closeMenu);
  }

  /* FAQ accordion */
  document.querySelectorAll(".faq-item").forEach(item=>{
    item.querySelector(".faq-q").addEventListener("click", ()=>{
      item.classList.toggle("open");
    });
  });

  /* Reveal on scroll */
  const revealEls = document.querySelectorAll(".reveal");
  if("IntersectionObserver" in window){
    const io = new IntersectionObserver((entries)=>{
      entries.forEach(e=>{ if(e.isIntersecting){ e.target.classList.add("in"); io.unobserve(e.target); } });
    }, {threshold:.12});
    revealEls.forEach(el=>io.observe(el));
  } else {
    revealEls.forEach(el=>el.classList.add("in"));
  }

  /* ---------- Simulator ---------- */
  const amountEl = document.getElementById("sim-amount");
  const durationEl = document.getElementById("sim-duration");
  const amountVal = document.getElementById("sim-amount-val");
  const durationVal = document.getElementById("sim-duration-val");
  const monthlyOut = document.getElementById("sim-monthly");

  function computeMonthly(){
    if(!amountEl || !durationEl) return;
    const amount = parseFloat(amountEl.value);
    const months = parseInt(durationEl.value, 10);
    const annualRate = 0.049; // taux indicatif / indikativer Zinssatz
    const monthlyRate = annualRate / 12;
    const monthly = (amount * monthlyRate) / (1 - Math.pow(1 + monthlyRate, -months));
    amountVal.textContent = amount.toLocaleString("de-DE") + " €";
    durationVal.textContent = months + " " + translations.sim_months[document.documentElement.lang];
    monthlyOut.textContent = monthly.toLocaleString("de-DE", {maximumFractionDigits:0}) + " €";
  }
  if(amountEl && durationEl){
    amountEl.addEventListener("input", computeMonthly);
    durationEl.addEventListener("input", computeMonthly);
    computeMonthly();
  }

  /* ---------- Contact form -> Formspree ---------- */
  const form = document.getElementById("contact-form");
  if(form){
    const successEl = document.getElementById("form-success");
    const errorEl = document.getElementById("form-error");
    const submitBtn = form.querySelector('button[type="submit"]');

    form.addEventListener("submit", (e)=>{
      e.preventDefault();
      const lang = document.documentElement.lang;
      successEl.style.display = "none";
      errorEl.style.display = "none";
      const originalLabel = submitBtn.textContent;
      submitBtn.textContent = translations.f_sending[lang];
      submitBtn.disabled = true;

      fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: { "Accept": "application/json" }
      }).then(response=>{
        if(response.ok){
          successEl.textContent = translations.f_success[lang];
          successEl.style.display = "block";
          form.reset();
        } else {
          errorEl.textContent = translations.f_error[lang];
          errorEl.style.display = "block";
        }
      }).catch(()=>{
        errorEl.textContent = translations.f_error[lang];
        errorEl.style.display = "block";
      }).finally(()=>{
        submitBtn.textContent = originalLabel;
        submitBtn.disabled = false;
      });
    });
  }
});
